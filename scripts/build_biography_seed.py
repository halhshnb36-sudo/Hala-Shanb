#!/usr/bin/env python3
"""
Builds supabase/migrations/006_seed_biography.sql from supabase/seed/biography_source.txt.

The source text is copied WITHOUT changes to wording or paragraph order. Only structural markers are
added so the website can style it:
  "## "  before the section headings        (the 10 headings, matched by exact text)
  "### " before the closing brand line
  "> "   before the closing slogan
Line 1 is stored as the title and line 3 as the subtitle. The remaining text is the body.

Usage:  python3 scripts/build_biography_seed.py
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "supabase" / "seed" / "biography_source.txt"
OUT = ROOT / "supabase" / "migrations" / "006_seed_biography.sql"

HEADINGS = {
    "البداية من مكان صغير... والطموح كان أكبر من البداية",
    "فرصة جديدة في قلب القاهرة... وخطوة نحو خبرة أكبر",
    "حين تجاوز الحلم حدود النجاح الشخصي",
    "من داخل المنزل بدأت خطوة جديدة في الحكاية",
    "الجودة والثقة... أساس العلاقة مع العميلات",
    "من عميلة إلى أخرى... بدأ الاسم يكتسب مكانته",
    "هالة شنب للعناية بالشعر... أكثر من مجرد اسم",
    "الحلم الأكبر... صالون يحمل اسمها",
    "النجاح الذي تتمناه... أن تكبر ويكبر معها أثرها",
    "حكاية لم تصل إلى فصلها الأخير",
}
SIGNATURE = "هالة شنب للعناية بالشعر"
SLOGAN = "استعيدي جمال وقوة شعرك مع هالة شنب."

lines = SRC.read_text(encoding="utf-8").replace("\r\n", "\n").split("\n")
while lines and lines[-1].strip() == "":
    lines.pop()

title = lines[0].strip()
subtitle = lines[2].strip()
assert title == "ما لا تعرفه عن هالة شنب", title
assert subtitle.startswith("حكاية طموح بدأ منذ الطفولة"), subtitle
assert lines[-1].strip() == SLOGAN, lines[-1]
assert lines[-3].strip() == SIGNATURE, lines[-3]

body_src = lines[4:]
body_out = []
found = set()
for i, line in enumerate(body_src):
    s = line.strip()
    is_last_signature = (i == len(body_src) - 3)
    if s in HEADINGS:
        found.add(s)
        body_out.append("## " + s)
    elif is_last_signature and s == SIGNATURE:
        body_out.append("### " + s)
    elif i == len(body_src) - 1 and s == SLOGAN:
        body_out.append("> " + s)
    else:
        body_out.append(line)

missing = HEADINGS - found
assert not missing, f"headings not found: {missing}"

body = "\n".join(body_out)

# --- self-check: removing the markers must give back the original text exactly ---
def strip_markers(text: str) -> str:
    out = []
    for l in text.split("\n"):
        for p in ("### ", "## ", "> "):
            if l.startswith(p):
                l = l[len(p):]
                break
        out.append(l)
    return "\n".join(out)

assert strip_markers(body) == "\n".join(body_src), "text changed while adding markers!"
for tag in ("$bio_t$", "$bio_s$", "$bio_b$"):
    assert tag not in body

sql = f"""-- 006_seed_biography.sql — GENERATED by scripts/build_biography_seed.py (do not edit by hand)
-- The complete Arabic biography as the initial PUBLISHED article. Editable later from /admin/biography.

insert into public.articles (kind, slug, title, subtitle, body, status, published_at, seo_title, seo_description)
values (
  'biography',
  'biography',
  $bio_t${title}$bio_t$,
  $bio_s${subtitle}$bio_s$,
  $bio_b${body}$bio_b$,
  'published',
  now(),
  $bio_t${title} | هالة شنب للعناية بالشعر$bio_t$,
  $bio_s${subtitle}$bio_s$
)
on conflict (slug) do nothing;
"""
OUT.write_text(sql, encoding="utf-8")
print(f"OK: wrote {OUT.relative_to(ROOT)} ({len(body_src)} body lines, {len(found)} headings)")
